!this is just a wrapper, it calls the ders later	
!Ntot is total number in array
subroutine derivs(u,du,dx, Ntot,dir,Nx,ind,iHor)
use m_pars, only : derorder
real*8, dimension(:), intent(in) :: u
real*8, dimension(:), intent(inout) :: du
real*8 :: dx
integer :: i,j,nx,dir,Ntot,ind
integer,dimension(:), intent(in)::iHor	   
du = 0.0

if (derorder.eq.1) then
	call derivs12(u(:),du(:),dx,Ntot,NX)
else if(derorder.eq.2) then
	call derivs24(u(:),du(:),dx,Ntot,NX)
else if(derorder.eq.3) then
	call derivs36(u(:),du(:),dx,Ntot,NX,ind,iHor)
else if(derorder.eq.4) then
	call derivs48(u(:),du(:),dx,Ntot,NX)
else if(derorder.eq.41) then
	call derivs48_b(u(:),du(:),dx,Ntot,NX)
end if

if(Nx.lt.Ntot) then
	du(Nx+1:Ntot) = du(Nx)
end if	

end subroutine derivs



	
subroutine derivs12(u,du,dx, Ntot, Nx)
real*8, dimension(:), intent(in) :: u
real*8, dimension(:), intent(inout) :: du
real*8 :: dx
integer :: i, Ntot, nx
	
do i = 2, nx-1
	du(i) = (u(i+1)-u(i-1))/dx*0.5
end do

du(1) = (u(2)-u(1))/dx
du(nx) = (u(nx)-u(nx-1))/dx
	
!use periodic bcs
!	du(1) = 0.5*(u(2)-u(nx-1))/dx
!	du(nx) = 0.5*(u(2)-u(nx-1))/dx

end subroutine derivs12
	
		
subroutine dissip(u,du,dx, Ntot,aa,Nx)
use m_pars, only : dissorder
	
real*8, dimension(:), intent(in) :: u
real*8, dimension(:), intent(inout) :: du
real*8 :: dx
integer :: i, j, Nx,aa,Ntot
real*8, allocatable, dimension(:,:) :: tempu
	

!do each dimension and then add
if (dissorder.eq.4) then
	call dissip4(u(:),du(:),dx,Ntot,NX)	
